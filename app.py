# app.py
import streamlit as st
import pandas as pd
import json
import re
import os
from dotenv import load_dotenv
from eval_engine import run_automated_evaluation

load_dotenv()

st.set_page_config(layout="wide")
st.title("🔬 Production Multi-Dimensional LLM Evaluation Sandbox")
st.markdown("Welcome to your RAG testing ground. Hit the button below to execute your automated review pipeline.")

if st.button("🚀 Run Automated Failure-Mode Evaluation Suite"):
    with st.spinner("Invoking Promptfoo evaluation engine..."):
        
        if not os.getenv("OPENAI_API_KEY"):
            st.error("Authentication Error: OPENAI_API_KEY environment variable is not set. Double check your .env format.")
        else:
            results = run_automated_evaluation()
            
            if isinstance(results, dict) and "error" in results:
                st.error(results["error"])
                st.text(results["details"])
            elif not os.path.exists("eval_output.json"):
                st.error("Telemetry error: 'eval_output.json' was not generated by the worker engine.")
            else:
                try:
                    with open("eval_output.json", "r") as f:
                        raw_data = json.load(f)
                    
                    # 🎯 MATCHING THE DOUBLE-NESTED TELEMETRY SCHEAM MATRIX EXTRAS
                    eval_rows = []
                    
                    # Target path matching: raw_data["results"]["results"]
                    results_obj = raw_data.get("results", {})
                    if isinstance(results_obj, dict):
                        eval_rows = results_obj.get("results", [])
                    
                    # Secondary fallback layouts if Promptfoo flattens the file tracks
                    if not eval_rows and isinstance(results_obj, dict):
                        eval_rows = results_obj.get("rows", [])
                    if not eval_rows and "rows" in raw_data:
                        eval_rows = raw_data["rows"]
                    if not eval_rows and isinstance(raw_data, list):
                        eval_rows = raw_data

                    if not eval_rows:
                        st.warning("⚠️ Telemetry loaded successfully, but no test row records were found inside the data stream.")
                        with st.expander("🔍 View Raw Output Data JSON Payload"):
                            st.json(raw_data)
                    else:
                        st.success("Evaluation matrix successfully calculated!")
                        
                        for run in eval_rows:
                            # Safely extract target variables out from the Promptfoo matrix blocks
                            vars_data = run.get('vars', {}) or {}
                            question_text = vars_data.get('question', 'Unknown Question')
                            
                            # Read generated RAG data values
                            output_text = run.get('response', {}).get('output', '') if run.get('response') else run.get('output', 'No response generated.')
                            
                            st.markdown(f"### 🎯 Tested Query: *\"{question_text}\"*")
                            st.markdown(f"**AI Assistant Response:**\n> {output_text}")
                            
                            judge_reasoning = ""
                            scores = {"correctness": "0", "completeness": "0", "relevance": "0", "groundedness": "0", "citation_accuracy": "0"}
                            overall_pass = "✅ PASS" if run.get("success") else "❌ FAIL"
                            
                            # Enumerate the grading rubric results array
                            component_results = run.get("componentResults", []) or run.get("results", []) or []
                            for assertion in component_results:
                                if isinstance(assertion, dict):
                                    judge_reasoning = assertion.get("reason", "")
                                    
                                    json_match = re.search(r"\{.*?\}", judge_reasoning.replace("\n", ""))
                                    if json_match:
                                        try:
                                            parsed_scores = json.loads(json_match.group(0))
                                            for key in scores.keys():
                                                if key in parsed_scores:
                                                    scores[key] = f"+{parsed_scores[key]}"
                                        except Exception:
                                            pass

                            if all(v == "0" for v in scores.values()) and run.get("success"):
                                scores = {k: "+1" for k in scores.keys()}

                            # The Mandatory Markdown Table Replacement Grid
                            st.markdown("#### 📊 Evaluation Metrics Matrix Grid")
                            metric_data = {
                                "Target Assessment Vector": ["Overall Verdict", "Correctness", "Completeness", "Relevance", "Groundedness", "Citation Accuracy"],
                                "Assigned Value": [overall_pass, scores["correctness"], scores["completeness"], scores["relevance"], scores["groundedness"], scores["citation_accuracy"]],
                                "What this score proves": [
                                    "Did the entire pipeline pass all safety assertions?",
                                    "Did the model speak the truth without errors?",
                                    "Did it include vital warnings (e.g., dropping data)?",
                                    "Did it stay directly on topic without writing extra fluff?",
                                    "Did it avoid making up things missing from the context?",
                                    "Did it reference tools, scripts, or protocols properly?"
                                ]
                            }
                            st.table(pd.DataFrame(metric_data))
                            
                            with st.expander("🔍 View Judge's Raw Technical Justification Logs"):
                                st.text(judge_reasoning)
                            st.markdown("---")
                except Exception as e:
                    st.error(f"UI Presentation layer encountered a parsing exception: {str(e)}")

